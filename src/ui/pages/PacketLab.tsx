import { useMemo, useState } from 'react';
import { CAPTURE_PRESETS, runCapture } from '../../engine/lab/captures';
import { FilterError, matchFilter, parseFilter } from '../../engine/filter';
import { buildPcap, frameBytes } from '../../engine/pcap';
import type { CapturedFrame } from '../../engine/types';
import { HexDump, PacketLayers } from '../components/PacketLayers';

function proto(f: CapturedFrame): string {
  if (f.arp) return 'ARP';
  const p = f.ip!;
  if (p.app?.protocol === 'SSH') return 'SSHv2';
  if (p.app?.protocol === 'DNS') return 'DNS';
  if (p.app?.protocol === 'DHCP') return 'DHCP';
  if (p.app?.protocol === 'DHCPv6') return 'DHCPv6';
  if (p.app?.protocol === 'TLS') return 'TLSv1.3';
  if (p.app?.protocol === 'KRB5') return 'KRB5';
  if (p.app?.protocol === 'KADMIN') return 'KADMIN';
  if (p.app?.protocol === 'RDP') return 'RDP';
  if (p.app?.protocol === 'NTP') return 'NTP';
  if (p.app?.protocol === 'SYSLOG') return 'Syslog';
  if (p.app?.protocol === 'SMB2') return 'SMB2';
  if (p.app?.protocol === 'DATA') return p.tcp?.sport === 80 || p.tcp?.dport === 80 ? 'HTTP' : 'DATA';
  if (p.icmp && p.src.includes(':')) return 'ICMPv6';
  return p.proto.toUpperCase();
}

function info(f: CapturedFrame): string {
  if (f.arp) return f.arp.op === 'request' ? `Who has ${f.arp.targetIp}? Tell ${f.arp.senderIp}` : `${f.arp.senderIp} is at ${f.arp.senderMac}`;
  const p = f.ip!;
  if (p.app) return p.app.info;
  if (p.tcp) return `${p.tcp.sport} → ${p.tcp.dport} [${p.tcp.flags.join(', ')}] Seq=${p.tcp.seq} ${p.tcp.flags.includes('ACK') ? `Ack=${p.tcp.ack} ` : ''}Win=${p.tcp.window} Len=${p.tcp.len}`;
  if (p.icmp?.nd?.target) return `${p.icmp.description} ${p.icmp.type === 135 ? `for ${p.icmp.nd.target}` : `${p.icmp.nd.target} is at ${p.icmp.nd.lladdr}`}`;
  if (p.icmp?.nd?.prefixes) return `${p.icmp.description} from ${p.icmp.nd.lladdr}, prefix ${p.icmp.nd.prefixes.map((x) => x.prefix).join(', ')}`;
  if (p.icmp) return `${p.icmp.description}${p.icmp.id !== undefined ? ` id=${p.icmp.id}, seq=${p.icmp.seq}` : ''}${p.icmp.quoted ? ` (for ${p.icmp.quoted.proto.toUpperCase()} ${p.icmp.quoted.dst}:${p.icmp.quoted.dport ?? ''})` : ''}`;
  if (p.udp) return `${p.udp.sport} → ${p.udp.dport} Len=${p.udp.len}`;
  return '';
}

export function PacketLab() {
  const [presetId, setPresetId] = useState(CAPTURE_PRESETS[0].id);
  const [filterText, setFilterText] = useState('');
  const [sel, setSel] = useState<number | null>(null);
  const cap = useMemo(() => runCapture(presetId), [presetId]);
  let filterError: string | null = null;
  let node = null;
  try {
    node = parseFilter(filterText);
  } catch (e) {
    filterError = e instanceof FilterError ? e.message : String(e);
  }
  const rows = cap.frames.map((f, i) => ({ f, i })).filter(({ f, i }) => filterError || matchFilter(node, f, i));
  const t0 = cap.frames[0]?.time ?? 0;
  const selected = sel !== null ? cap.frames[sel] : null;

  const download = () => {
    const bytes = buildPcap(cap.frames);
    const blob = new Blob([bytes], { type: 'application/vnd.tcpdump.pcap' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `infralab-${presetId}.pcap`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  };

  return (
    <div className="page wide">
      <h1>Packet Lab</h1>
      <p className="muted">
        Synthetic, protocol-consistent captures generated by the simulator (not recordings of real traffic). Headers, checksums, sequence numbers, ICMP quoting
        and plaintext SSH negotiation messages are real encodings; cryptographic values and encrypted payloads are pseudo-random bytes of realistic length.
        Exported files open in Wireshark.
      </p>
      <div className="row" style={{ marginBottom: 8 }}>
        <select value={presetId} onChange={(e) => { setPresetId(e.target.value); setSel(null); }}>
          {CAPTURE_PRESETS.map((p) => <option key={p.id} value={p.id}>{p.title}</option>)}
        </select>
        <input className="mono" style={{ minWidth: 340 }} placeholder="Display filter, e.g. tcp.flags.syn == 1 || icmp" value={filterText} onChange={(e) => setFilterText(e.target.value)} />
        <button onClick={download}>Export .pcap</button>
        <span className="small muted">Captured on {cap.preset.host}:{cap.preset.iface} · {rows.length}/{cap.frames.length} shown</span>
      </div>
      {filterError && <div className="feedback bad small">{filterError}</div>}
      <div className="grid2" style={{ gridTemplateColumns: 'minmax(0,1.4fr) minmax(0,1fr)' }}>
        <div>
          <div className="card small" style={{ marginBottom: 8 }}>
            <strong>{cap.preset.title}.</strong> {cap.preset.description}
            <div className="muted" style={{ marginTop: 4 }}>Look for: {cap.preset.lookFor.join(' · ')}</div>
          </div>
          <div className="card" style={{ padding: 0, maxHeight: 520, overflow: 'auto' }}>
            <table className="pkt-table">
              <thead><tr><th>No.</th><th>Time</th><th>Source</th><th>Destination</th><th>Protocol</th><th>Len</th><th>Info</th></tr></thead>
              <tbody>
                {rows.map(({ f, i }) => {
                  const cls = f.ip?.tcp?.flags.includes('RST') ? 'rst' : f.ip?.icmp && f.ip.icmp.type !== 0 && f.ip.icmp.type !== 8 ? 'icmperr' : '';
                  return (
                    <tr key={i} className={`${sel === i ? 'sel' : ''} ${cls}`} onClick={() => setSel(i)}>
                      <td>{i + 1}</td>
                      <td>{((f.time - t0) / 1000).toFixed(6)}</td>
                      <td>{f.arp ? f.srcMac : f.ip!.src}</td>
                      <td>{f.arp ? (f.dstMac === 'ff:ff:ff:ff:ff:ff' ? 'Broadcast' : f.dstMac) : f.ip!.dst}</td>
                      <td>{proto(f)}</td>
                      <td>{frameBytes(f).length}</td>
                      <td>{info(f)}</td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
        <div className="inspector">
          {!selected ? <div className="muted">Select a packet to see its layers and bytes.</div> : (
            <>
              <h3 style={{ marginTop: 0 }}>Frame {sel! + 1}: {frameBytes(selected).length} bytes on wire ({selected.dir === 'in' ? 'received' : 'sent'} on {selected.iface})</h3>
              <PacketLayers packet={selected.ip} arp={selected.arp} vlan={selected.vlan} l2={[{ src: selected.srcMac, dst: selected.dstMac, note: selected.iface }]} />
              <details className="layer" open><summary>Bytes</summary><div style={{ padding: 8 }}><HexDump bytes={frameBytes(selected)} /></div></details>
            </>
          )}
          <div className="callout small" style={{ marginTop: 10 }}>
            <strong>What a capture can and cannot tell you.</strong> Visible without keys: addresses, ports, TCP flags and timing, DNS questions and answers,
            ICMP errors, SSH versions and algorithm lists, the server host key. Not visible: anything after SSH New Keys (user name, auth method result,
            commands). Those require endpoint evidence such as the sshd journal.
          </div>
        </div>
      </div>
    </div>
  );
}
