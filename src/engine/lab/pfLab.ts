export function installFw01(world: World, cfg: PfConfig = productionConfig()): Host {
  const t = world.clock;
  world.segments.dmz50 ??= { id: 'dmz50', name: 'DMZ (fw01 opt1)', cidr: '172.16.50.0/24' };
  const fw = createHost(world, {
    id: 'fw01', hostname: 'fw01', domain: 'corp.lab', kind: 'pfsense', osName: `pfSense ${PF_VERSION} (amd64)`,
    role: 'Perimeter firewall (pfSense): WAN, LAN (server network) and DMZ',
    ifaces: [{ name: 'vtnet0', mac: '52:54:00:9f:00:0a', segment: 'wan' }, { name: 'vtnet1', mac: '52:54:00:9f:01:fe', segment: 'srv20' }, { name: 'vtnet2', mac: '52:54:00:9f:02:01', segment: 'dmz50' }],
    services: ['ssh'],
  });
  // FreeBSD, not Debian: drop the Linux configuration createHost writes.
  for (const p of Object.keys(fw.fs)) if (/^\/etc\/(network|nftables\.conf|sysctl\.d|nginx|dhcp|default|systemd)|^\/lib\/systemd|^\/usr\/lib\/systemd/.test(p)) delete fw.fs[p];
  for (const d of ['/conf', '/cf', '/cf/conf', '/cf/conf/backup', '/sbin', '/usr/local', '/usr/local/sbin', '/usr/local/www', '/var/etc', '/etc/inc']) mkdir(fw, d, t);
  writeFile(fw, '/conf/config.xml', toXml(cfg), t);
  writeFile(fw, '/etc/version', `${PF_VERSION.replace('-RELEASE', '')}-RELEASE\n`, t);
  writeFile(fw, '/etc/platform', 'pfSense\n', t);
  writeFile(fw, '/etc/resolv.conf', `domain ${cfg.domain}\n${cfg.dnsservers.map((d) => `nameserver ${d}`).join('\n')}\n`, t);
  writeFile(fw, '/etc/ssh/sshd_config', PF_SSHD_CONFIG, t);
  writeFile(fw, '/usr/local/www/index.html', LOGIN_PAGE, t);
  writeFile(fw, '/var/log/filter.log', '', t, { mode: 0o600, group: 'wheel' });
  writeFile(fw, '/var/log/system.log', '', t, { mode: 0o600, group: 'wheel' });
  writeFile(fw, '/etc/motd', '', t);
  for (const b of ['/bin/tcsh', '/bin/csh', '/etc/rc.initial', '/etc/rc.filter_configure', '/etc/rc.reload_all', '/sbin/pfctl', '/usr/local/sbin/easyrule', '/usr/local/sbin/viconfig']) writeFile(fw, b, '', t, { mode: 0o755 });
  installHostKeys(fw, t);
  fw.users.root = { ...fw.users.root, password: FW01_ADMIN_PASSWORD, shell: '/bin/tcsh', primaryGroup: 'wheel', groups: ['wheel', 'admins'] };
  addUser(fw, { name: 'admin', uid: 0, gid: 0, primaryGroup: 'wheel', groups: ['wheel', 'admins'], home: '/root', shell: '/etc/rc.initial', gecos: 'System Administrator', password: FW01_ADMIN_PASSWORD }, t, false);
  return fw;
}

export function installDmz01(world: World): Host {
  const t = world.clock;
  world.segments.dmz50 ??= { id: 'dmz50', name: 'DMZ (fw01 opt1)', cidr: '172.16.50.0/24' };
  const h = createHost(world, {
    id: 'dmz01', hostname: 'dmz01', domain: 'corp.lab', role: 'Public web server in the DMZ (portal.corp.lab)',
    ifaces: [{ name: 'eth0', mac: '52:54:00:d5:00:0a', segment: 'dmz50' }], services: ['ssh', 'nginx'],
  });
  writeFile(h, '/etc/network/interfaces', staticInterfaces([{ name: 'eth0', address: `${DMZ01_IP}/24`, gateway: '172.16.50.1' }]), t);
  writeFile(h, '/etc/resolv.conf', 'search corp.lab\nnameserver 10.0.10.53\n', t);
  writeFile(h, '/etc/ssh/sshd_config', DEBIAN_SSHD_CONFIG, t);
  installHostKeys(h, t);
  writeFile(h, '/etc/nginx/nginx.conf', 'user www-data;\nworker_processes auto;\nhttp {\n    server {\n        listen 80 default_server;\n        server_name portal.corp.lab;\n        root /var/www/html;\n    }\n}\n', t);
  writeFile(h, '/var/www/html/index.html', '<!DOCTYPE html>\n<html><head><title>Corp Lab customer portal</title></head>\n<body><h1>Corp Lab customer portal</h1><p>Served by dmz01 in the DMZ.</p></body></html>\n', t);
  addUser(h, { name: 'alice', uid: 1000, gid: 1000, primaryGroup: 'alice', groups: ['sudo'], home: '/home/alice', shell: '/bin/bash', gecos: 'Alice Admin', password: 'dmz01-alice' }, t);
  return h;
}
