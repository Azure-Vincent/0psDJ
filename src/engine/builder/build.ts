// Turn a builder design into a running simulated network. Every setting is
// written as the configuration file a Debian administrator would write
// (/etc/network/interfaces, /etc/nftables.conf, sysctl, ifupdown2 bridge
// config), then the machines boot from those files: what runs is exactly
// what the files say, and the learner can inspect or change them in the terminals.

