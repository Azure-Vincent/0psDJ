import { DEBIAN_SSHD_CONFIG, installHostKeys } from '../lab/sshLab';
import { mkdir, writeFile } from '../fs';
import { recomputeL2 } from '../sim/l2';
import { bootHost } from '../sim/services';
import { Shell } from '../shell/shell';
import { Recorder, withRecorder, type TraceEvent } from '../sim/trace';
import type { Host, World } from '../types';
import { addressOf, ifaceFor, isSubInterface, physicalOf, validateDesign, vlanOfIface, type AllowRule, type Design, type DesignNode, type Diagnostic, type ForwardRule } from './design';

export const BUILDER_DOMAIN = 'lab.test';
export const BUILDER_USER = 'admin';
export const BUILDER_PASSWORD = 'admin';
const START = '2026-10-19T07:58:00Z';
const KIND_ORDER: Record<DesignNode['kind'], number> = { switch: 0, router: 1, server: 2, host: 3 };

function mac(nodeIdx: number, ifIdx: number): string {
  const h = (n: number) => n.toString(16).padStart(2, '0');
  return `52:54:00:${h(0x60 + Math.floor(nodeIdx / 256))}:${h(nodeIdx % 256)}:${h(ifIdx + 1)}`;
}

/** /etc/network/interfaces for a host, server or router. */
export function interfacesFile(n: DesignNode): string {
  const lines = [
    '# This file describes the network interfaces available on your system',
    '# and how to activate them. For more information, see interfaces(5).',
    `# Generated by the Infrastructure Builder for ${n.name}.`,
    '',
    'source /etc/network/interfaces.d/*',
    '',
    '# The loopback network interface',
    'auto lo',
    'iface lo inet loopback',
  ];
  const gwIface = n.gateway?.trim() ? ifaceFor(n, n.gateway.trim()) : null;
  for (const i of n.ifaces) {
    const addr = i.address?.trim();
    lines.push('');
    const vid = vlanOfIface(i.name);
    if (vid !== null) lines.push(`# ${i.name}: VLAN ${vid} tagged on ${physicalOf(i.name)}`);
    lines.push(`auto ${i.name}`);
    if (!addr) {
      lines.push(`iface ${i.name} inet manual`);
      continue;
    }
    lines.push(`iface ${i.name} inet static`, `    address ${addr}`);
    if (gwIface === i.name) lines.push(`    gateway ${n.gateway!.trim()}`);
    for (const r of n.routes ?? []) if (ifaceFor(n, r.via.trim()) === i.name) lines.push(`    up ip route add ${r.dest.trim()} via ${r.via.trim()}`);
  }
  return lines.join('\n') + '\n';
}

/** ifupdown2 configuration of a switch: a VLAN-aware bridge over all its ports. */
export function switchInterfacesFile(n: DesignNode, labels: Record<string, string>): string {
  const ports = n.ports ?? [];
  const vids = [...new Set(ports.flatMap((p) => (p.mode === 'access' ? [p.vlan ?? 1] : p.vlans ?? [])))].filter((v) => v !== 1).sort((a, b) => a - b);
  const lines = [`# ${n.name} - switch (Linux bridge with VLAN filtering, ifupdown2)`, '# Generated by the Infrastructure Builder.', '', 'auto lo', 'iface lo inet loopback'];
  for (const p of ports) {
    lines.push('', `auto ${p.name}`, `iface ${p.name}`);
    if (labels[p.name]) lines.push(`    alias ${labels[p.name]}`);
    if (p.mode === 'access') lines.push(`    bridge-access ${p.vlan ?? 1}`);
    else lines.push(`    bridge-vids ${(p.vlans ?? []).join(' ')}`);
  }
  lines.push('', 'auto br0', 'iface br0', '    bridge-vlan-aware yes', `    bridge-ports ${ports.map((p) => p.name).join(' ')}`);
  if (vids.length) lines.push(`    bridge-vids ${vids.join(' ')}`);
  lines.push('    bridge-pvid 1');
  return lines.join('\n') + '\n';
}

function ruleMatch(r: { proto: string; port?: number; from?: string; to?: string }): string {
  const parts: string[] = [];
  if (r.from?.trim()) parts.push(`ip saddr ${r.from.trim()}`);
  if (r.to?.trim()) parts.push(`ip daddr ${r.to.trim()}`);
  if (r.proto === 'icmp') parts.push('meta l4proto icmp');
  else if (r.proto !== 'any') parts.push(r.port !== undefined ? `${r.proto} dport ${r.port}` : `meta l4proto ${r.proto}`);
  return parts.join(' ');
}

function describeAllow(r: AllowRule | ForwardRule): string {
  const what = r.proto === 'any' ? 'all traffic' : r.port !== undefined ? `${r.proto}/${r.port}` : r.proto;
  return `${what}${r.from?.trim() ? ` from ${r.from.trim()}` : ''}${'to' in r && r.to?.trim() ? ` to ${r.to.trim()}` : ''}`;
}

/** /etc/nftables.conf: input filter (when enabled), forward filter and NAT (routers). */
export function nftablesFile(n: DesignNode): string {
  const fw = n.firewall;
  const router = n.kind === 'router';
  if (!fw?.enabled && !(router && (n.forward?.policy === 'drop' || n.forward?.allow.length || n.nat?.outIface))) return DEBIAN_DEFAULT_NFT;
  const L: string[] = ['#!/usr/sbin/nft -f', `# Generated by the Infrastructure Builder for ${n.name}.`, '', 'flush ruleset', '', 'table inet filter {', '\tchain input {'];
  if (fw?.enabled) {
    L.push('\t\ttype filter hook input priority filter; policy drop;', '\t\tct state established,related accept', '\t\tiif "lo" accept');
    for (const r of fw.allow) L.push(`\t\t# allow ${describeAllow(r)}`, `\t\t${ruleMatch(r)} accept`);
  } else L.push('\t\ttype filter hook input priority filter; policy accept;');
  L.push('\t}', '\tchain forward {');
  if (router) {
    const policy = n.forward?.policy ?? 'accept';
    L.push(`\t\ttype filter hook forward priority filter; policy ${policy};`);
    if (policy === 'drop') L.push('\t\tct state established,related accept');
    for (const r of n.forward?.allow ?? []) L.push(`\t\t# allow ${describeAllow(r)}`, `\t\t${ruleMatch(r) ? ruleMatch(r) + ' ' : ''}accept`);
  } else L.push('\t\ttype filter hook forward priority filter;');
  L.push('\t}', '\tchain output {', '\t\ttype filter hook output priority filter; policy accept;', '\t}', '}');
  if (router && n.nat?.outIface) {
    L.push('', `# Source NAT: traffic leaving ${n.nat.outIface} gets ${n.name}'s address on that interface`, 'table ip nat {', '\tchain postrouting {', '\t\ttype nat hook postrouting priority srcnat; policy accept;', `\t\toifname "${n.nat.outIface}" masquerade`, '\t}', '}');
  }
  return L.join('\n') + '\n';
}

export function hostsFile(design: Design, self: DesignNode): string {
  const lines = ['127.0.0.1\tlocalhost', `127.0.1.1\t${self.name}.${BUILDER_DOMAIN}\t${self.name}`, '', '# Every machine of the design (first address), generated by the Infrastructure Builder'];
  for (const n of design.nodes) {
    const ip = n.ifaces.map(addressOf).find(Boolean);
    if (ip && n.id !== self.id) lines.push(`${ip}\t${n.name}.${BUILDER_DOMAIN}\t${n.name}`);
  }
  lines.push('', '# The following lines are desirable for IPv6 capable hosts', '::1     localhost ip6-localhost ip6-loopback', 'ff02::1 ip6-allnodes', 'ff02::2 ip6-allrouters');
  return lines.join('\n') + '\n';
}

const NGINX_CONF = `user www-data;
worker_processes auto;
http {
    server {
        listen 80 default_server;
        root /var/www/html;
    }
}
`;

const ROLE: Record<DesignNode['kind'], string> = {
  host: 'Workstation (designed in the Infrastructure Builder)',
  server: 'Server (designed in the Infrastructure Builder)',
  router: 'Router (designed in the Infrastructure Builder)',
  switch: 'Switch (Linux bridge with VLAN filtering)',
};

export interface BuildResult {
  world: World | null;
  diagnostics: Diagnostic[];
}

export function buildDesignWorld(design: Design): BuildResult {
  const diagnostics = validateDesign(design);
  if (diagnostics.some((d) => d.level === 'error')) return { world: null, diagnostics };
  const world = newWorld(design.name || 'Builder design', START);
  const t = world.clock;
  const byId = new Map(design.nodes.map((n) => [n.id, n]));
  const nodes = [...design.nodes].sort((a, b) => KIND_ORDER[a.kind] - KIND_ORDER[b.kind]);

  // Cables: to a switch port → world.links; machine to machine → a private segment.
  world.links = [];
  const p2p = new Map<string, string>();
  const portLabel: Record<string, Record<string, string>> = {};
  for (const l of design.links) {
    const a = byId.get(l.a.node)!, b = byId.get(l.b.node)!;
    if (a.kind === 'switch' || b.kind === 'switch') {
      const [sw, m] = a.kind === 'switch' ? [l.a, l.b] : [l.b, l.a];
      world.links.push({ a: { host: byId.get(m.node)!.name, iface: m.iface }, b: { host: byId.get(sw.node)!.name, iface: sw.iface } });
      (portLabel[sw.node] ??= {})[sw.iface] = `${byId.get(m.node)!.name} ${m.iface}`;
    } else {
      p2p.set(`${a.id}/${l.a.iface}`, `link-${l.id}`);
      p2p.set(`${b.id}/${l.b.iface}`, `link-${l.id}`);
    }
  }

  const hosts: Host[] = [];
  nodes.forEach((n, idx) => {
    if (n.kind === 'switch') {
      const sw = createHost(world, {
        id: n.name, hostname: n.name, domain: BUILDER_DOMAIN, role: ROLE.switch, kind: 'switch',
        ifaces: (n.ports ?? []).map((p, k) => ({ name: p.name, mac: mac(idx, k), segment: null })),
        services: [],
      });
      writeFile(sw, '/etc/network/interfaces', switchInterfacesFile(n, portLabel[n.id] ?? {}), t);
      writeFile(sw, '/etc/resolv.conf', '', t);
      hosts.push(sw);
      return;
    }
    const services = ['nftables', ...(n.services?.includes('ssh') ? ['ssh'] : []), ...(n.services?.includes('web') ? ['nginx'] : [])];
    const phys = n.ifaces.filter((i) => !isSubInterface(i.name));
    const h = createHost(world, {
      id: n.name, hostname: n.name, domain: BUILDER_DOMAIN, role: ROLE[n.kind], kind: n.kind === 'router' ? 'router' : 'linux',
      ifaces: phys.map((i, k) => ({ name: i.name, mac: mac(idx, k), segment: p2p.get(`${n.id}/${i.name}`) ?? null })),
      services,
    });
    writeFile(h, '/etc/network/interfaces', interfacesFile(n), t);
    writeFile(h, '/etc/resolv.conf', `search ${BUILDER_DOMAIN}\n`, t);
    writeFile(h, '/etc/hosts', hostsFile(design, n), t);
    writeFile(h, '/etc/nftables.conf', nftablesFile(n), t, { mode: 0o755 });
    if (n.kind === 'router') writeFile(h, '/etc/sysctl.d/99-router.conf', '# This machine routes between its networks\nnet.ipv4.ip_forward=1\n', t);
    if (n.services?.includes('ssh')) {
      writeFile(h, '/etc/ssh/sshd_config', DEBIAN_SSHD_CONFIG, t);
      installHostKeys(h, t);
    }
    if (n.services?.includes('web')) {
      mkdir(h, '/etc/nginx', t);
      writeFile(h, '/etc/nginx/nginx.conf', NGINX_CONF, t);
      writeFile(h, '/var/www/html/index.html', `<!DOCTYPE html>\n<html><head><title>${n.name}</title></head>\n<body><h1>Hello from ${n.name}</h1></body></html>\n`, t);
    }
    if (n.kind !== 'router') addUser(h, { name: BUILDER_USER, uid: 1000, gid: 1000, primaryGroup: BUILDER_USER, groups: ['sudo'], home: `/home/${BUILDER_USER}`, shell: '/bin/bash', gecos: 'Lab Administrator', password: BUILDER_PASSWORD }, t);
    hosts.push(h);
  });

  recomputeL2(world);
  for (const h of hosts) bootHost(world, h);
  world.clock += 60_000;
  return { world, diagnostics };
}

/** Reboot every machine of a builder world (switches first, then routers, then the rest). */
export function rebootDesignWorld(world: World): World {
  const w = structuredClone(world);
  w.sessions = [];
  const rank = (h: Host) => (h.kind === 'switch' ? 0 : h.kind === 'router' ? 1 : 2);
  for (const h of Object.values(w.hosts).sort((a, b) => rank(a) - rank(b))) bootHost(w, h);
  w.clock += 30_000;
  return w;
}

/** The user a terminal on this machine logs in as. */
export function loginUser(world: World, hostId: string): string {
  return world.hosts[hostId]?.users[BUILDER_USER] ? BUILDER_USER : 'root';
}

export interface TraceResult {
  events: TraceEvent[];
  output: string;
  /** Firewall, NAT and drop decisions along the way, in first-seen order (repeats counted). */
  decisions: { host: string; note: string; count: number }[];
}

const DECISION = /hook|masquerade|snat|dnat|nat|dropped|reject|forwarding is disabled|no route/i;
// A chain without rules that lets everything through decides nothing worth listing.
const NO_OP = /^(input|forward) hook: nft inet filter \w+: no rule matched, chain policy accept; (delivered to the local socket layer)?$/;

/** The decision part of a hop note (without the TTL and routing details). */
function decisionText(note: string): string {
  return note.replace(/^TTL \d+→\d+; /, '').replace(/; routed via [^;]*/, '');
}

/**
 * Run one command with the packet recorder on a copy of the world: the trace
 * shows every packet and every firewall decision, and the learner's machines
 * are left untouched.
 */
export function traceCommand(world: World, hostId: string, user: string, line: string): TraceResult {
  let w = structuredClone(world);
  for (const h of Object.values(w.hosts)) h.capture = [];
  const sh = new Shell(() => w, (n) => (w = n), { hostId, user, cwd: w.hosts[hostId].users[user]?.home ?? '/' });
  const rec = new Recorder();
  const r = withRecorder(rec, () => sh.execute(line));
  const decisions: TraceResult['decisions'] = [];
  const add = (host: string, note: string) => {
    const d = decisions.find((x) => x.host === host && x.note === note);
    if (d) d.count += 1;
    else decisions.push({ host, note, count: 1 });
  };
  for (const ev of rec.events) {
    const hops = (ev.hops ?? []).filter((h) => DECISION.test(h.note));
    for (const hop of hops) {
      const text = decisionText(hop.note);
      if (!NO_OP.test(text)) add(hop.host, text);
    }
    if (ev.delivered === false && ev.outcome && !hops.length) add(ev.to, ev.outcome);
  }
  return { events: rec.events, output: r.output, decisions };
}

/** Broadcast domain an interface is in, for the sequence diagram's layer-2 notes. */
export function segmentLabel(world: World, hostId: string, iface?: string): string {
  const i = world.hosts[hostId]?.ifaces.find((x) => x.name === iface);
  if (!i?.segment) return '';
  const m = /^(.+)-vlan(\d+)$/.exec(i.segment);
  if (m) return `VLAN ${m[2]} on ${m[1]}`;
  if (i.segment.startsWith('link-')) return 'direct cable';
  return i.segment;
}
