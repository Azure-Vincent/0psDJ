// systemd unit files for the simulated services, as shipped by Debian 12
// packages. They are written to each host's filesystem so `systemctl cat`,
// `ls /lib/systemd/system` and `cat` show the same text, and so dependency
// queries (`systemctl list-dependencies`, `systemctl show`) read the real
// [Unit] directives. The simulator does not re-execute the Exec* lines; each
// service's start/reload behaviour is modelled in services.ts to match them.

