/** Install the unit files of the host's services, and the sshd PAM configuration. */
export function installUnits(host: Host, t: number): void {
  for (const d of ['/lib', '/lib/systemd', '/lib/systemd/system', '/etc/systemd', '/etc/systemd/system', '/run', '/run/systemd', '/run/systemd/generator.late', '/etc/pam.d']) {
    if (!host.fs[d]) mkdir(host, d, t);
  }
  for (const name of Object.keys(host.services)) {
    const u = UNITS[name];
    if (!u) continue;
    writeFile(host, u.path, u.text, t);
  }
  if (host.services.ssh) writeFile(host, '/etc/pam.d/sshd', PAM_SSHD, t);
  writeFile(host, '/etc/pam.d/common-auth', PAM_COMMON_AUTH, t);
}

export function unitPath(name: string): string | undefined {
  return UNITS[name]?.path;
}

export function unitWantedBy(name: string): string {
  return UNITS[name]?.wantedBy ?? 'multi-user.target';
}

/** Parse [Unit] dependency directives from the unit file on disk (plus drop-ins). */
export function unitDirectives(host: Host, name: string, unit: string): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  const files = [unitPath(name), ...dropIns(host, unit)].filter((p): p is string => !!p);
  for (const f of files) {
    const text = readFile(host, f);
    if (!text) continue;
    for (const line of text.split('\n')) {
      const m = /^([A-Za-z]+)=(.*)$/.exec(line.trim());
      if (!m) continue;
      out[m[1]] = [...(out[m[1]] ?? []), ...m[2].split(/\s+/).filter(Boolean)];
    }
  }
  return out;
}

/** Drop-in files: /etc/systemd/system/<unit>.d/*.conf (what `systemctl edit` creates). */
export function dropIns(host: Host, unit: string): string[] {
  const dir = `/etc/systemd/system/${unit}.d/`;
  return Object.keys(host.fs).filter((p) => p.startsWith(dir) && p.endsWith('.conf') && host.fs[p].type === 'file').sort();
}
