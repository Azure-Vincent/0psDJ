// electron-builder afterPack hook (Linux only).
//
// Chromium sandboxes its renderers with unprivileged user namespaces, or else
// with the setuid-root helper "chrome-sandbox". Distributions such as Ubuntu
// 23.10+/24.04 restrict unprivileged user namespaces through AppArmor, and an
// AppImage cannot ship a setuid-root helper (it runs from a FUSE mount), so
// Electron aborts with "The SUID sandbox helper binary was found, but is not
// configured correctly".
//
// We install a small launcher in place of the Electron binary. It starts the
// app normally whenever a sandbox can work, and adds --no-sandbox only when
// neither mechanism is available (or when running as root, which Chromium
// refuses to sandbox). The app only loads its own bundled, offline pages and
// opens external links in the system browser.

const fs = require('node:fs');
const path = require('node:path');

const LAUNCHER = `#!/bin/sh
# Infrastructure Lab launcher (generated by build/afterPack.cjs).
HERE="$(dirname "$(readlink -f "$0")")"
BIN="$HERE/__EXE__.bin"

sandbox_available() {
  # A setuid-root chrome-sandbox (e.g. tar.gz install where an admin ran
  # "sudo chown root:root chrome-sandbox && sudo chmod 4755 chrome-sandbox").
  if [ -u "$HERE/chrome-sandbox" ] && [ "$(stat -c %u "$HERE/chrome-sandbox" 2>/dev/null)" = "0" ]; then
    return 0
  fi
  # Otherwise Chromium needs unprivileged user namespaces.
  [ "$(cat /proc/sys/kernel/unprivileged_userns_clone 2>/dev/null)" = "0" ] && return 1
  [ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = "1" ] && return 1
  [ "$(cat /proc/sys/user/max_user_namespaces 2>/dev/null)" = "0" ] && return 1
  return 0
}

for arg in "$@"; do
  [ "$arg" = "--no-sandbox" ] && exec "$BIN" "$@"
done

if [ "$(id -u)" = "0" ]; then
  exec "$BIN" --no-sandbox "$@"
fi
if sandbox_available; then
  exec "$BIN" "$@"
fi
echo "Infrastructure Lab: this system restricts unprivileged user namespaces and no setuid chrome-sandbox is available; starting with --no-sandbox." >&2
exec "$BIN" --no-sandbox "$@"
`;

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'linux') return;
  const exe = context.packager.executableName;
  const exePath = path.join(context.appOutDir, exe);
  const binPath = `${exePath}.bin`;
  if (!fs.existsSync(binPath)) fs.renameSync(exePath, binPath);
  fs.writeFileSync(exePath, LAUNCHER.replace('__EXE__', exe), { mode: 0o755 });
};
